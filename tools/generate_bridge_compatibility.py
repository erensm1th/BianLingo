"""Generate the addon compatibility constants from the release configuration."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def render(root=ROOT):
    config = json.loads((root/'resources/bridge-compatibility.json').read_text(encoding='utf8'))
    version = re.search(r'project\(BianLingo VERSION ([0-9]+\.[0-9]+\.[0-9]+)',
                        (root/'CMakeLists.txt').read_text(encoding='utf8')).group(1)
    if config['schemaVersion'] != 1 or not 1 <= config['protocolMin'] <= config['protocolMax'] <= 65535:
        raise ValueError('Invalid compatibility policy')
    for field in ['minimumDesktop', 'minimumAddon']:
        if not re.fullmatch(r'[0-9]{1,5}\.[0-9]{1,5}\.[0-9]{1,5}',config[field]):
            raise ValueError('Invalid compatibility version')
        if any(int(n) > 65535 for n in config[field].split('.')):
            raise ValueError('Invalid compatibility version')
        if tuple(map(int,config[field].split('.'))) > tuple(map(int,version.split('.'))):
            raise ValueError('Current release does not meet its own compatibility policy')
    return ('-- Generated by tools/generate_bridge_compatibility.py.\nBLGCompatibility = {\n'
            f'    version = "{version}", minimumDesktop = "{config["minimumDesktop"]}",\n'
            f'    minimumAddon = "{config["minimumAddon"]}", protocolMin = {config["protocolMin"]}, protocolMax = {config["protocolMax"]}\n'
            '}\n')

if __name__ == '__main__':
    (ROOT/'addon/BianLingo/Compatibility.lua').write_text(render(),encoding='utf8')
